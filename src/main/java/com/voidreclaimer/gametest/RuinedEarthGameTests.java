package com.voidreclaimer.gametest;

import com.voidreclaimer.VoidReclaimer;
import com.voidreclaimer.earth.RuinedEarth;
import com.voidreclaimer.earth.RuinedEarthChunkGenerator;
import com.voidreclaimer.earth.RuinedTerrain;
import com.voidreclaimer.registry.ModBlocks;
import com.voidreclaimer.space.ZeroGravity;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.UpgradeData;
import net.minecraft.world.level.chunk.ProtoChunk;
import net.neoforged.neoforge.gametest.GameTestHolder;
import net.neoforged.neoforge.gametest.PrefixGameTestTemplate;

/** Phase 11 slice: the ruined_earth dimension, its terrain and its gravity. */
@GameTestHolder(VoidReclaimer.MOD_ID)
@PrefixGameTestTemplate(false)
public final class RuinedEarthGameTests {
    private RuinedEarthGameTests() {}

    private static ServerLevel earth(GameTestHelper helper) {
        ServerLevel level = helper.getLevel().getServer().getLevel(RuinedEarth.DIMENSION);
        if (level == null) {
            throw new AssertionError("ruined_earth is not loaded; is the mod's datapack disabled?");
        }
        return level;
    }

    /** Fills a fresh proto chunk, because the persistent GameTest world would hand back chunks generated by an older run. */
    private static ChunkAccess generate(ServerLevel earth, int chunkX, int chunkZ) {
        ProtoChunk chunk = new ProtoChunk(new ChunkPos(chunkX, chunkZ), UpgradeData.EMPTY, earth,
                earth.registryAccess().registryOrThrow(Registries.BIOME), null);
        RuinedEarthChunkGenerator.fillTerrain(earth.getSeed(), chunk);
        return chunk;
    }

    @GameTest(template = "empty", timeoutTicks = 200)
    public static void dimensionUsesTheRuinedGenerator(GameTestHelper helper) {
        ServerLevel earth = earth(helper);
        helper.assertTrue(earth.getChunkSource().getGenerator() instanceof RuinedEarthChunkGenerator, "wrong chunk generator");
        helper.succeed();
    }

    @GameTest(template = "empty", timeoutTicks = 200)
    public static void terrainIsSlagOnStoneInsideThePlanetAndVoidOutside(GameTestHelper helper) {
        ServerLevel earth = earth(helper);
        long seed = earth.getSeed();
        int x = 8;
        int z = 8;
        ChunkAccess inside = generate(earth, x >> 4, z >> 4);
        int top = RuinedTerrain.surfaceY(seed, x, z);
        helper.assertTrue(inside.getBlockState(new BlockPos(x, top, z)).is(ModBlocks.ASHEN_SLAG.get()), "no slag on the surface");
        helper.assertTrue(inside.getBlockState(new BlockPos(x, top + 1, z)).isAir(), "block above the surface");
        helper.assertTrue(inside.getBlockState(new BlockPos(x, top - 10, z)).is(Blocks.STONE), "no stone under the slag");
        helper.assertTrue(inside.getBlockState(new BlockPos(x, earth.getMinBuildHeight(), z)).is(Blocks.BEDROCK), "no bedrock floor");

        int outsideX = RuinedTerrain.HALF + 40;
        ChunkAccess outside = generate(earth, outsideX >> 4, 0);
        helper.assertTrue(outside.getBlockState(new BlockPos(outsideX, RuinedTerrain.BASE_Y, 8)).isAir(), "terrain outside the planet");
        helper.succeed();
    }

    @GameTest(template = "empty", timeoutTicks = 200)
    public static void gravityWorksOnRuinedEarth(GameTestHelper helper) {
        ServerLevel earth = earth(helper);
        BlockPos pos = new BlockPos(8, RuinedTerrain.BASE_Y + 20, 8);
        helper.assertFalse(ZeroGravity.isZeroG(earth, pos), "ruined earth is zero-G");
        earth.getChunk(pos.getX() >> 4, pos.getZ() >> 4);
        ItemEntity item = new ItemEntity(earth, pos.getX() + 0.5, pos.getY(), pos.getZ() + 0.5, new ItemStack(Items.STONE));
        earth.addFreshEntity(item);
        helper.assertFalse(item.isNoGravity(), "item has no gravity on ruined earth");
        item.discard();
        helper.succeed();
    }
}
